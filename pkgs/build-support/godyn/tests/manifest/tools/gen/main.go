// Command gen writes generated.go for the manifest fixture: a go:generate
// generator the codegen drift check runs inside the vendored module tree
// (FDR 0008).
package main

import "os"

func main() {
	const src = "// Code generated by tools/gen. DO NOT EDIT.\n\npackage main\n\nconst generated = \"generated by tools/gen\"\n"
	if err := os.WriteFile("generated.go", []byte(src), 0o644); err != nil {
		panic(err)
	}
}
